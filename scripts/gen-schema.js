'use strict';
// Regenerates src/schema-sqlite.js (the schema as a JS string, because Cloudflare has no file system) from db/schema.sqlite.sql.
const fs = require('fs'), path = require('path');
const sql = fs.readFileSync(path.join(__dirname, '..', 'db', 'schema.sqlite.sql'), 'utf8');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'schema-sqlite.js'), "'use strict';\n// GENERATED by scripts/gen-schema.js from db/schema.sqlite.sql - do not edit by hand.\nmodule.exports = " + JSON.stringify(sql) + ";\n");
console.log('src/schema-sqlite.js written');
